// Usage: bun run scripts/embed-registry.ts  (writes src/embedded-registry.ts from the registry branch)
const url = "https://raw.githubusercontent.com/CUNY-AI-Lab/eco-impact-openwebui/registry/eco_models.json";
const response = await fetch(url);
if (!response.ok) throw new Error(`registry fetch failed: ${response.status}`);
const text = await response.text();
const body = `// Generated by scripts/embed-registry.ts from ${url}. Do not edit by hand.\nimport type { Registry } from "./registry.js";\nexport const EMBEDDED_REGISTRY: Registry = ${JSON.stringify(JSON.parse(text))} as Registry; // SAFETY: generated from the validated weekly registry\n`;
await Bun.write(new URL("../src/embedded-registry.ts", import.meta.url), body);
